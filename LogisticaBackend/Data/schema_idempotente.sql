-- ==============================================================================
-- Script SQL Idempotente de Migración de Esquema para Logística y Movilidad
-- ==============================================================================
-- Este script es completamente aditivo, seguro y reversible.
-- No borra ni modifica la tabla heredada 'liquidaciones_viaje'.
-- ==============================================================================

-- 1. Tabla Principal de Planillas de Viaje
CREATE TABLE IF NOT EXISTS planillas_viaje (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicial date NOT NULL,
    fecha_final date NOT NULL,
    placa character varying(10) NOT NULL,
    conductor character varying(150) NOT NULL,
    manifiesto character varying(50) NULL,
    empresa_transportadora character varying(150) NULL,
    origen character varying(100) NULL,
    destino character varying(100) NULL,
    flete numeric(14,2) NOT NULL DEFAULT 0.00,
    anticipo numeric(14,2) NOT NULL DEFAULT 0.00,
    total_gastos numeric(14,2) NOT NULL DEFAULT 0.00,
    saldo_viaje numeric(14,2) NOT NULL DEFAULT 0.00,
    saldo_anterior numeric(14,2) NOT NULL DEFAULT 0.00,
    saldo_total numeric(14,2) NOT NULL DEFAULT 0.00,
    estado_revision character varying(20) NOT NULL DEFAULT 'Aprobado',
    json_ocr_crudo jsonb NULL,
    creado_en timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Tabla 1:N de Gastos Dinámicos
CREATE TABLE IF NOT EXISTS gastos_detalle (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planilla_viaje_id integer NOT NULL,
    concepto character varying(150) NOT NULL,
    concepto_canonico character varying(50) NOT NULL DEFAULT 'OTROS',
    valor numeric(14,2) NOT NULL DEFAULT 0.00,
    orden integer NOT NULL DEFAULT 0,
    CONSTRAINT fk_gastos_detalle_planillas_viaje_id 
        FOREIGN KEY (planilla_viaje_id) 
        REFERENCES planillas_viaje (id) 
        ON DELETE CASCADE
);

-- 3. Índices Idempotentes para Búsquedas Frecuentes
CREATE INDEX IF NOT EXISTS ix_planillas_viaje_placa ON planillas_viaje (placa);
CREATE INDEX IF NOT EXISTS ix_planillas_viaje_manifiesto ON planillas_viaje (manifiesto);
CREATE INDEX IF NOT EXISTS ix_planillas_viaje_fecha_inicial ON planillas_viaje (fecha_inicial);
CREATE INDEX IF NOT EXISTS ix_gastos_detalle_planilla_viaje_id ON gastos_detalle (planilla_viaje_id);
CREATE INDEX IF NOT EXISTS ix_gastos_detalle_concepto_canonico ON gastos_detalle (concepto_canonico);

